"""TRAIN-ONLY BSAA PPG-HR prototype. Run from project root:

python -m databasing.elgendi.run_prototype --database data/hr_database_seg10s_step5s.parquet \
    --edf-root data/harmonized_ecg_ppg_database_filtered

Requires the EDF files and HR parquet generated by the existing pipeline.
Writes only new files under results/elgendi_train/. Never writes to EDF/test/manifest.
"""
import argparse
import csv
import json
from pathlib import Path
from collections import defaultdict

import numpy as np
import pandas as pd
import pyarrow.dataset as ds

from databasing.elgendi.detection import ElgendiConfig, detect_ppg_peaks
from databasing.pan_tompkins.heart_rate import compute_hr_segments
from utils.read_edf import read_edf_signals

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_MANIFEST = PROJECT_ROOT / 'databasing/references/split_manifest.csv'
DEFAULT_EDF = PROJECT_ROOT / 'data/harmonized_ecg_ppg_database_filtered'
DEFAULT_DB = PROJECT_ROOT / 'data/hr_database_seg10s_step5s.parquet'


def read_train_manifest(path):
    allowed = set()
    with open(path, newline='', encoding='utf-8') as f:
        for row in csv.DictReader(f):
            if row['set'] == 'train':
                allowed.add(row['file'].replace('\\', '/'))
    if not allowed:
        raise ValueError('No training files in manifest')
    return allowed


def evaluate(dataset_path, edf_root, manifest, output, config=ElgendiConfig(), limit_files=None):
    """Restrict to TRAIN in both Parquet and original subject-wise manifest."""
    allowed = read_train_manifest(manifest)
    dataset = ds.dataset(str(dataset_path), format='parquet')
    needed = ['base_folder', 'edf_filename', 'start', 'end', 'sampling_rate',
              'hr_bpm', 'hr_valid', 'ppg_is_flat']
    absent = sorted(set(needed + ['split']) - set(dataset.schema.names))
    if absent:
        raise ValueError(f'Missing Parquet columns: {absent}')
    # Push down split restriction: never compute with test data.
    df = dataset.to_table(columns=needed, filter=ds.field('split') == 'train').to_pandas()
    if df.empty:
        raise ValueError('No training rows in Parquet')
    df['relative_file'] = df['base_folder'].astype(str) + '/' + df['edf_filename'].astype(str)
    invalid = set(df['relative_file']) - allowed
    if invalid:
        raise ValueError(f'Parquet TRAIN disagrees with manifest for: {sorted(invalid)[:5]}')
    groups = df.groupby('relative_file', sort=True)
    if limit_files is not None:
        groups = list(groups)[:limit_files]
    records = []
    missing = []
    for rel, rows in groups:
        # Safe lookup: paths come from validated manifest, no test folder searched.
        edf_path = (edf_root / rel).resolve()
        if not edf_path.is_relative_to(edf_root.resolve()):
            raise ValueError(f'Unsafe path: {rel}')
        if not edf_path.is_file():
            missing.append(rel)
            continue
        _, ppg, meta = read_edf_signals(str(edf_path))
        if ppg is None or meta is None:
            missing.append(rel)
            continue
        fs = float(meta['sampling_rate'])
        if not np.allclose(rows['sampling_rate'].to_numpy(dtype=float), fs):
            raise ValueError(f'Sampling rate mismatch: {rel}')
        # EDFs supplied here MUST be prefiltered, NOT raw recordings.
        peaks = detect_ppg_peaks(ppg, fs, config)
        for row in rows.itertuples(index=False):
            start, end = int(row.start), int(row.end)
            if start < 0 or end > len(ppg) or end <= start:
                raise ValueError(f'Invalid segment boundaries for {rel}: {start}:{end}')
            # Evaluate exactly the same segment and inclusion rules as ECG code.
            local_peaks = peaks[(peaks >= start) & (peaks < end)] - start
            length = end - start
            ppg_stats = compute_hr_segments(local_peaks, length, fs,
                                            segment_s=length / fs,
                                            step_s=length / fs)
            estimate = ppg_stats.iloc[0]
            valid_ecg = bool(row.hr_valid) and np.isfinite(row.hr_bpm)
            valid_ppg = bool(estimate['valid']) and not bool(row.ppg_is_flat)
            accepted = valid_ecg and valid_ppg
            ppg_hr = float(estimate['hr_bpm']) if valid_ppg else np.nan
            records.append({
                'relative_file': rel, 'start': start, 'end': end,
                'sampling_rate': fs, 'ecg_hr_bpm': float(row.hr_bpm) if valid_ecg else np.nan,
                'ecg_hr_valid': valid_ecg, 'ppg_hr_bpm': ppg_hr,
                'ppg_hr_valid': valid_ppg, 'ppg_n_beats': int(estimate['n_beats']),
                'ppg_invalid_reason': 'flat_ppg' if bool(row.ppg_is_flat) else str(estimate['invalid_reason']),
                'evaluated': accepted, 'error_bpm': (ppg_hr - float(row.hr_bpm)) if accepted else np.nan,
            })
    if not records:
        raise ValueError('No records processed: check the prefiltered EDF root and Parquet paths')
    out = pd.DataFrame.from_records(records)
    errors = out.loc[out['evaluated'], 'error_bpm'].to_numpy(dtype=float)
    report = {
        'scope': 'TRAIN ONLY - developmental performance, not held-out test',
        'n_train_windows': len(out),
        'n_ecg_reference_valid': int(out['ecg_hr_valid'].sum()),
        'n_ppg_valid': int(out['ppg_hr_valid'].sum()),
        'n_paired_windows': int(out['evaluated'].sum()),
        'coverage_of_ecg_valid': (float(out['evaluated'].sum() / out['ecg_hr_valid'].sum())
                                  if out['ecg_hr_valid'].sum() else None),
        'mae_bpm': float(np.mean(np.abs(errors))) if len(errors) else None,
        'rmse_bpm': float(np.sqrt(np.mean(errors ** 2))) if len(errors) else None,
        'bias_bpm': float(np.mean(errors)) if len(errors) else None,
        'missing_edf_count': len(missing), 'missing_edf_examples': missing[:10],
        'detector_parameters': vars(config),
        'note': 'Overlapping windows are correlated; metrics are development-only. No test data used.'
    }
    output.mkdir(parents=True, exist_ok=True)
    out.to_csv(output / 'train_window_predictions.csv', index=False)
    (output / 'train_metrics.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--database', type=Path, default=DEFAULT_DB)
    parser.add_argument('--edf-root', type=Path, default=DEFAULT_EDF,
                        help='Root of ALREADY FILTERED EDFs; never point to raw data')
    parser.add_argument('--manifest', type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument('--output', type=Path, default=PROJECT_ROOT / 'results/elgendi_train')
    parser.add_argument('--limit-files', type=int, default=None,
                        help='Optional quick smoke run on first N training EDFs')
    parser.add_argument('--peakwindow', type=float, default=0.111)
    parser.add_argument('--beatwindow', type=float, default=0.667)
    parser.add_argument('--beatoffset', type=float, default=0.02)
    parser.add_argument('--mindelay', type=float, default=0.3)
    args = parser.parse_args()
    config = ElgendiConfig(args.peakwindow, args.beatwindow, args.beatoffset, args.mindelay)
    report = evaluate(args.database, args.edf_root, args.manifest, args.output, config, args.limit_files)
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
